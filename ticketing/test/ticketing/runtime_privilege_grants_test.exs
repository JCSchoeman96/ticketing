defmodule Ticketing.RuntimePrivilegeGrantFlowConfigTest do
  use ExUnit.Case, async: true

  test "owner migration aliases apply runtime grants before application setup" do
    aliases = Mix.Project.config() |> Keyword.fetch!(:aliases)

    for {alias_name, migration_step} <- [
          setup: "ecto.migrate -r Ticketing.MigrationRepo",
          "ecto.setup": "ecto.migrate -r Ticketing.MigrationRepo",
          test: "ecto.migrate -r Ticketing.MigrationRepo --quiet"
        ] do
      steps = Keyword.fetch!(aliases, alias_name)
      migration_index = Enum.find_index(steps, &(&1 == migration_step))
      grant_index = Enum.find_index(steps, &(&1 == "ticketing.db.grant_runtime_privileges"))

      assert is_integer(migration_index), "#{alias_name} must migrate through MigrationRepo"
      assert is_integer(grant_index), "#{alias_name} must apply runtime privileges"
      assert migration_index < grant_index
    end
  end
end

defmodule Ticketing.RuntimePrivilegeGrantTest do
  use ExUnit.Case, async: false

  alias Ecto.Adapters.SQL
  alias Ecto.Adapters.SQL.Sandbox
  alias Ecto.Migrator
  alias Ticketing.MigrationRepo
  alias Ticketing.Platform.DatabasePrivileges

  @fixture_table "t0_01_runtime_privilege_fixture"
  @fixture_sequence "t0_01_runtime_privilege_fixture_id_seq"

  test "migration owner grants runtime DML and sequence use without granting ownership or DDL" do
    with_migration_repo(fn repo ->
      SQL.query!(repo, "DROP TABLE IF EXISTS public.#{@fixture_table}", [])

      SQL.query!(
        repo,
        """
        CREATE TABLE public.#{@fixture_table} (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          value text NOT NULL
        )
        """,
        []
      )
    end)

    :ok = Sandbox.checkout(Ticketing.Repo)

    try do
      with_migration_repo(fn repo ->
        assert :ok = DatabasePrivileges.apply!(repo)
        assert :ok = DatabasePrivileges.apply!(repo)
      end)

      assert %Postgrex.Result{rows: [[id]]} =
               SQL.query!(
                 Ticketing.Repo,
                 "INSERT INTO public.#{@fixture_table} (value) VALUES ($1) RETURNING id",
                 ["created"]
               )

      assert %Postgrex.Result{rows: [["created"]]} =
               SQL.query!(
                 Ticketing.Repo,
                 "SELECT value FROM public.#{@fixture_table} WHERE id = $1",
                 [id]
               )

      assert %Postgrex.Result{num_rows: 1} =
               SQL.query!(
                 Ticketing.Repo,
                 "UPDATE public.#{@fixture_table} SET value = $1 WHERE id = $2",
                 ["updated", id]
               )

      assert %Postgrex.Result{rows: [["updated"]]} =
               SQL.query!(
                 Ticketing.Repo,
                 "SELECT value FROM public.#{@fixture_table} WHERE id = $1",
                 [id]
               )

      assert %Postgrex.Result{num_rows: 1} =
               SQL.query!(
                 Ticketing.Repo,
                 "DELETE FROM public.#{@fixture_table} WHERE id = $1",
                 [id]
               )

      runtime_user = Application.fetch_env!(:ticketing, Ticketing.Repo)[:username]

      assert %Postgrex.Result{
               rows: [
                 [
                   current_user,
                   superuser,
                   bypass_rls,
                   createdb,
                   createrole,
                   owner_member,
                   owns_fixture,
                   database_connect,
                   schema_usage,
                   schema_create,
                   migration_metadata_select,
                   table_select,
                   table_insert,
                   table_update,
                   table_delete,
                   table_truncate,
                   table_references,
                   table_trigger,
                   table_maintain,
                   sequence_usage,
                   sequence_select,
                   sequence_update
                 ]
               ]
             } =
               SQL.query!(
                 Ticketing.Repo,
                 """
                 SELECT current_user,
                        role.rolsuper,
                        role.rolbypassrls,
                        role.rolcreatedb,
                        role.rolcreaterole,
                        pg_has_role(current_user, $1::name, 'MEMBER'),
                        EXISTS (
                          SELECT 1
                          FROM pg_class AS relation
                          JOIN pg_namespace AS namespace ON namespace.oid = relation.relnamespace
                          WHERE namespace.nspname = 'public'
                            AND relation.relname = $2
                            AND relation.relowner = role.oid
                        ),
                        has_database_privilege(current_user, current_database(), 'CONNECT'),
                        has_schema_privilege(current_user, 'public', 'USAGE'),
                        has_schema_privilege(current_user, 'public', 'CREATE'),
                        has_table_privilege(current_user, 'public.schema_migrations', 'SELECT'),
                        has_table_privilege(current_user, 'public.' || $2, 'SELECT'),
                        has_table_privilege(current_user, 'public.' || $2, 'INSERT'),
                        has_table_privilege(current_user, 'public.' || $2, 'UPDATE'),
                        has_table_privilege(current_user, 'public.' || $2, 'DELETE'),
                        has_table_privilege(current_user, 'public.' || $2, 'TRUNCATE'),
                        has_table_privilege(current_user, 'public.' || $2, 'REFERENCES'),
                        has_table_privilege(current_user, 'public.' || $2, 'TRIGGER'),
                        has_table_privilege(current_user, 'public.' || $2, 'MAINTAIN'),
                        has_sequence_privilege(current_user, 'public.' || $3, 'USAGE'),
                        has_sequence_privilege(current_user, 'public.' || $3, 'SELECT'),
                        has_sequence_privilege(current_user, 'public.' || $3, 'UPDATE')
                 FROM pg_roles AS role
                 WHERE role.rolname = current_user
                 """,
                 [
                   System.get_env("TICKETING_TEST_MIGRATION_DB_USER", "ticketing_test"),
                   @fixture_table,
                   @fixture_sequence
                 ]
               )

      assert current_user == runtime_user
      refute superuser
      refute bypass_rls
      refute createdb
      refute createrole
      refute owner_member
      refute owns_fixture
      assert database_connect
      assert schema_usage
      refute schema_create
      refute migration_metadata_select
      assert table_select
      assert table_insert
      assert table_update
      assert table_delete
      refute table_truncate
      refute table_references
      refute table_trigger
      refute table_maintain
      assert sequence_usage
      refute sequence_select
      refute sequence_update

      assert %Postgrex.Result{rows: [[9, 9, 9]]} =
               SQL.query!(
                 Ticketing.Repo,
                 """
                 SELECT count(*)::integer,
                        count(*) FILTER (
                          WHERE has_function_privilege('public', function.oid, 'EXECUTE')
                        )::integer,
                        count(*) FILTER (
                          WHERE has_function_privilege(current_user, function.oid, 'EXECUTE')
                        )::integer
                 FROM pg_catalog.pg_proc AS function
                 JOIN pg_catalog.pg_namespace AS namespace
                   ON namespace.oid = function.pronamespace
                 WHERE namespace.nspname = 'public'
                   AND function.proname IN (
                     'ash_elixir_or',
                     'ash_elixir_and',
                     'ash_trim_whitespace',
                     'ash_raise_error',
                     'ash_required',
                     'uuid_generate_v7'
                   )
                 """,
                 []
               )

      assert_raise Postgrex.Error, ~r/permission denied for schema public/, fn ->
        SQL.query!(
          Ticketing.Repo,
          "CREATE TABLE public.t0_runtime_must_not_create (id integer)",
          []
        )
      end
    after
      :ok = Sandbox.checkin(Ticketing.Repo)

      with_migration_repo(fn repo ->
        SQL.query!(repo, "DROP TABLE IF EXISTS public.#{@fixture_table}", [])
      end)
    end
  end

  defp with_migration_repo(fun) do
    assert {:ok, _, _} = Migrator.with_repo(MigrationRepo, fun)
  end
end
